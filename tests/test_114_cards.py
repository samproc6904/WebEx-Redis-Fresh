async def main():
    cards = [c.strip() for c in CARDS if c.strip()]
    total = len(cards)
    print(f"🔍 Testing {total} cards across {len(API_URLS)} API servers...")
    print(f"APIs: {', '.join(API_URLS)}")
    print(f"{'='*70}")

    results = {
        "CHARGED": [], "APPROVED": [], "DEAD": [], "ERROR": [],
    }
    start = time.time()
    done = 0

    # Check cards in batches of 20 (semaphore limit)
    sem = asyncio.Semaphore(20)

    async def check_one(card):
        nonlocal done
        site = random_site()
        async with sem:
            r = await check_card(card, site)
        done += 1
        status = r["status"]
        resp = r["response"]
        # Truncate response for display
        resp_short = resp[:60] + "..." if len(resp) > 60 else resp
        print(f"[{done:3d}/{total}] {card} => {status:10s} | {resp_short}")
        results[status].append(r)
        return r

    tasks = [check_one(c) for c in cards]
    await asyncio.gather(*tasks)

    elapsed = time.time() - start
    print(f"\n{'='*70}")
    print(f"📊 RESULTS SUMMARY")
    print(f"{'='*70}")
    print(f"Total:   {total}")
    print(f"CHARGED: {len(results['CHARGED'])}")
    print(f"APPROVED:{len(results['APPROVED'])}")
    print(f"DEAD:    {len(results['DEAD'])}")
    print(f"ERROR:   {len(results['ERROR'])}")
    print(f"Time:    {elapsed:.1f}s | Speed: {total/elapsed:.1f} cards/sec")

    if results["CHARGED"]:
        print(f"\n💰 CHARGED CARDS:")
        for r in results["CHARGED"]:
            print(f"  {r['card']} @ {r['site']} - {r['response']}")

    if results["APPROVED"]:
        print(f"\n✅ APPROVED CARDS:")
        for r in results["APPROVED"]:
            print(f"  {r['card']} @ {r['site']} - {r['response']}")

    # Show dead/error breakdown
    dead_responses = {}
    for r in results["DEAD"]:
        resp = r["response"][:50]
        dead_responses[resp] = dead_responses.get(resp, 0) + 1
    if dead_responses:
        print(f"\n💀 DEAD breakdown:")
        for resp, count in sorted(dead_responses.items(), key=lambda x: -x[1]):
            print(f"  {count:3d}x {resp}")

    err_responses = {}
    for r in results["ERROR"]:
        resp = r["response"][:50]
        err_responses[resp] = err_responses.get(resp, 0) + 1
    if err_responses:
        print(f"\n⚠️  ERROR breakdown:")
        for resp, count in sorted(err_responses.items(), key=lambda x: -x[1]):
            print(f"  {count:3d}x {resp}")

    print(f"\n{'='*70}")


if __name__ == "__main__":
    asyncio.run(main())
